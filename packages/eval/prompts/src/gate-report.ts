#!/usr/bin/env node
// `pnpm eval:gate`: runs Tessera's rules-only prompt gate over the dataset and
// writes docs/benchmarks/gate.md. Deterministic and model-free, so every number
// in the report is reproducible on any machine (timings aside).

import { writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { loadCore, type CoreLike } from './core.ts';
import { loadDataset } from './dataset.ts';
import { LANGS, STYLES, type PromptItem, type PromptStyle } from './types.ts';

type Verdict = 'ok_as_is' | 'improve' | 'ask';
const VERDICTS: Verdict[] = ['ok_as_is', 'improve', 'ask'];
const THRESHOLDS = [0.4, 0.5, 0.6, 0.7, 0.8];

export interface GateCounts {
  byStyle: Record<PromptStyle, Record<Verdict, number>>;
  n: Record<PromptStyle, number>;
}

export function countVerdicts(
  items: PromptItem[],
  gate: (text: string) => { verdict: Verdict },
): GateCounts {
  const byStyle = Object.fromEntries(
    STYLES.map((s) => [s, { ok_as_is: 0, improve: 0, ask: 0 }]),
  ) as GateCounts['byStyle'];
  const n = Object.fromEntries(STYLES.map((s) => [s, 0])) as GateCounts['n'];
  for (const it of items) {
    byStyle[it.style][gate(it.prompt).verdict]++;
    n[it.style]++;
  }
  return { byStyle, n };
}

const pct = (a: number, b: number) => (b ? `${Math.round((a / b) * 100)}%` : 'n/a');

/** The two numbers the gate is tuned on: vague prompts get flagged, well-specified ones are left alone. */
export function headline(c: GateCounts): { vagueFlagged: number; wellLeftAlone: number } {
  const v = c.byStyle.vague;
  return {
    vagueFlagged: c.n.vague ? (v.improve + v.ask) / c.n.vague : 0,
    wellLeftAlone: c.n['well-specified']
      ? c.byStyle['well-specified'].ok_as_is / c.n['well-specified']
      : 0,
  };
}

function render(core: CoreLike, items: PromptItem[], sha256: string): string {
  const def = countVerdicts(items, (t) => core.gatePrompt(t));
  const h = headline(def);
  const lines: string[] = [];
  lines.push('# Prompt gate benchmark');
  lines.push('');
  lines.push(
    'Generated by `pnpm eval:gate` from `packages/eval/prompts/data/prompts.jsonl`. Do not edit by hand.',
  );
  lines.push('');
  lines.push(
    'The gate is Tessera’s rules-only first pass (Tier 0). It decides whether a prompt is fine as it is, worth improving, or too ambiguous to improve without asking. It runs on every keystroke, so it has to be cheap, and it must leave good prompts alone: rewriting a well-specified prompt can only make it worse.',
  );
  lines.push('');
  lines.push(`- Dataset: ${items.length} prompts, sha256 \`${sha256.slice(0, 12)}\``);
  lines.push(`- Optimizer template: \`${core.OPTIMIZER_TEMPLATE_VERSION}\`, default threshold 0.6`);
  lines.push(
    `- **Vague prompts flagged (improve or ask): ${pct(h.vagueFlagged * def.n.vague, def.n.vague)}**`,
  );
  lines.push(
    `- **Well-specified prompts left alone: ${pct(h.wellLeftAlone * def.n['well-specified'], def.n['well-specified'])}**`,
  );
  lines.push('');
  lines.push('## Verdicts by prompt style (default threshold)');
  lines.push('');
  lines.push('| Style | n | ok as is | improve | ask |');
  lines.push('| --- | --: | --: | --: | --: |');
  for (const s of STYLES) {
    const r = def.byStyle[s];
    lines.push(
      `| ${s} | ${def.n[s]} | ${VERDICTS.map((v) => `${r[v]} (${pct(r[v], def.n[s])})`).join(' | ')} |`,
    );
  }
  lines.push('');
  lines.push(
    '“Typical” prompts are the grey zone by design: some are fine, some would benefit from a rewrite, so a roughly even split is expected.',
  );
  lines.push('');
  lines.push('## Threshold sweep');
  lines.push('');
  lines.push('| okThreshold | vague flagged | typical left alone | well-specified left alone |');
  lines.push('| --: | --: | --: | --: |');
  for (const t of THRESHOLDS) {
    const c = countVerdicts(items, (x) => core.gatePrompt(x, { okThreshold: t }));
    const hh = headline(c);
    lines.push(
      `| ${t.toFixed(1)}${t === 0.6 ? ' (default)' : ''} | ${pct(hh.vagueFlagged, 1)} | ${pct(c.byStyle.typical.ok_as_is, c.n.typical)} | ${pct(hh.wellLeftAlone, 1)} |`,
    );
  }
  lines.push('');
  lines.push('## By language (default threshold)');
  lines.push('');
  lines.push('| Language | n | vague flagged | well-specified left alone |');
  lines.push('| --- | --: | --: | --: |');
  for (const lang of LANGS) {
    const sub = items.filter((i) => i.lang === lang);
    if (!sub.length) continue;
    const c = countVerdicts(sub, (x) => core.gatePrompt(x));
    const v = c.byStyle.vague;
    lines.push(
      `| ${lang} | ${sub.length} | ${pct(v.improve + v.ask, c.n.vague)} of ${c.n.vague} | ${pct(c.byStyle['well-specified'].ok_as_is, c.n['well-specified'])} of ${c.n['well-specified']} |`,
    );
  }
  lines.push('');
  const misses = items.filter((it) => {
    const v = core.gatePrompt(it.prompt).verdict;
    return (
      (it.style === 'vague' && v === 'ok_as_is') ||
      (it.style === 'well-specified' && v !== 'ok_as_is')
    );
  });
  lines.push('## Misses');
  lines.push('');
  if (!misses.length) lines.push('None.');
  for (const m of misses) {
    const g = core.gatePrompt(m.prompt);
    const first = m.prompt.split('\n')[0]!.slice(0, 80);
    lines.push(`- \`${m.id}\` (${m.style}) → ${g.verdict}, score ${g.score}: “${first}”`);
  }
  lines.push('');
  // Timing: the gate runs on every keystroke, so its cost matters.
  const t0 = performance.now();
  const reps = 20;
  for (let r = 0; r < reps; r++) for (const it of items) core.gatePrompt(it.prompt);
  const perPromptUs = ((performance.now() - t0) * 1000) / (reps * items.length);
  lines.push('## Cost');
  lines.push('');
  lines.push(
    `About ${perPromptUs.toFixed(0)} µs per prompt on average (${os.cpus()[0]?.model.trim() ?? 'unknown CPU'}, Node ${process.version}). No model, no network.`,
  );
  lines.push('');
  lines.push('## Caveats');
  lines.push('');
  lines.push(
    '- The gate was tuned on this same dataset; there is no held-out set yet, so these numbers are optimistic. Adding fresh prompts (especially Tamil, Hindi and Hinglish) is the best way to keep it honest.',
  );
  lines.push('- The style labels were assigned by the dataset author, not by independent raters.');
  lines.push(
    '- This measures the gate’s decisions only. Whether a rewrite actually improves the chatbot’s answer is measured by `pnpm eval:prompts` (see prompt-quality.md), which needs a local model.',
  );
  lines.push('');
  return lines.join('\n');
}

async function main(): Promise<void> {
  const { values } = parseArgs({ options: { out: { type: 'string' } } });
  const here = path.dirname(fileURLToPath(import.meta.url));
  const { items, sha256 } = loadDataset(path.resolve(here, '../data/prompts.jsonl'));
  const core = await loadCore();
  const out = values.out ?? path.resolve(here, '../../../../docs/benchmarks/gate.md');
  writeFileSync(out, render(core, items, sha256));
  const h = headline(countVerdicts(items, (t) => core.gatePrompt(t)));
  console.info(
    `Wrote ${out}: vague flagged ${pct(h.vagueFlagged, 1)}, well-specified left alone ${pct(h.wellLeftAlone, 1)}`,
  );
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err: unknown) => {
    console.error(err);
    process.exit(1);
  });
}
