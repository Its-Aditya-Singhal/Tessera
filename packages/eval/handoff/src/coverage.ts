#!/usr/bin/env node
// `pnpm eval:capsule`: a model-free check of what Tessera's capsule keeps. For every question in
// the handoff dataset it asks whether the answer is still present in the handoff text (strings for
// facts and decisions, byte-exact for code) and whether a revised decision's final value appears
// after the stale one. It says nothing about whether a model will use the text well; that is
// what `pnpm eval:handoff` measures. Writes docs/benchmarks/capsule-coverage.md.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { loadCoreCapsule } from './tessera-capsule.ts';
import { approxTokens } from './tokens.ts';
import type { Conversation, Dataset, QuestionKind } from './types.ts';

type Mode = 'full' | 'capsule' | 'hybrid';

export interface CoverageRow {
  mode: Mode;
  kept: Record<QuestionKind, [number, number]>;
  /** Revised decisions where the last line mentioning either choice names the final one. */
  latestLast: [number, number];
  tokens: number;
  fullTokens: number;
}

const lower = (s: string) => s.toLowerCase();

export function coverage(
  conversations: readonly Conversation[],
  build: (c: Conversation) => string,
  mode: Mode,
  fullText: (c: Conversation) => string,
): CoverageRow {
  const kept: CoverageRow['kept'] = { fact: [0, 0], decision: [0, 0], code: [0, 0] };
  const latestLast: [number, number] = [0, 0];
  let tokens = 0;
  let fullTokens = 0;
  for (const c of conversations) {
    const text = build(c);
    const t = lower(text);
    tokens += approxTokens(text);
    fullTokens += approxTokens(fullText(c));
    for (const q of c.questions) {
      kept[q.kind][1]++;
      const ok =
        q.kind === 'code'
          ? Boolean(q.code) && text.includes(q.code!.code.replace(/\n$/, ''))
          : q.accept.some((a) => t.includes(lower(a)));
      if (ok) kept[q.kind][0]++;
      if (q.kind === 'decision' && q.stale) {
        latestLast[1]++;
        // The last line that mentions either choice must mention the final one
        // ("moving from SQLite to PostgreSQL" counts; a bare "SQLite it is" does not).
        const stale = lower(q.stale);
        const last = t
          .split('\n')
          .findLast((l) => l.includes(stale) || q.accept.some((a) => l.includes(lower(a))));
        if (last && q.accept.some((a) => last.includes(lower(a)))) latestLast[0]++;
      }
    }
  }
  return { mode, kept, latestLast, tokens, fullTokens };
}

const pct = ([a, b]: [number, number]) =>
  b ? `${((a / b) * 100).toFixed(1)}% (${a}/${b})` : 'n/a';

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: { out: { type: 'string' }, turns: { type: 'string', default: '4' } },
  });
  const here = path.dirname(fileURLToPath(import.meta.url));
  const dataset = JSON.parse(
    readFileSync(path.resolve(here, '../data/conversations.json'), 'utf8'),
  ) as Dataset;
  const { buildCapsule } = await loadCoreCapsule();
  const lastTurns = Number(values.turns);
  const run = (mode: Mode) => (c: Conversation) =>
    buildCapsule(c.messages, { mode, lastTurns, budgetTokens: 1_000_000 }).text;
  const rows = (['full', 'capsule', 'hybrid'] as const).map((m) =>
    coverage(dataset.conversations, run(m), m, run('full')),
  );
  const lines = [
    '# Capsule coverage',
    '',
    'Generated by `pnpm eval:capsule` from `packages/eval/handoff/data/conversations.json`. Do not edit by hand.',
    '',
    'A model-free check of what the handoff text keeps. For each of the 260 questions in the handoff dataset, is the answer still in the text Tessera would paste into the new chat? Facts and decisions are matched as strings, code must match byte for byte. “Latest wins” counts revised decisions where the last line mentioning either choice names the final one (a line like “moving from SQLite to PostgreSQL” counts), which is what the chronological order and the “(changed)” marker rely on.',
    '',
    `${dataset.conversations.length} conversations, hybrid keeps the last ${lastTurns} turns verbatim. No budget pressure: this measures what each mode keeps, not trimming.`,
    '',
    '| Mode | Facts kept | Decisions kept | Code kept (exact) | Latest wins | Tokens | vs full |',
    '| --- | --: | --: | --: | --: | --: | --: |',
    ...rows.map(
      (r) =>
        `| ${r.mode} | ${pct(r.kept.fact)} | ${pct(r.kept.decision)} | ${pct(r.kept.code)} | ${pct(r.latestLast)} | ${r.tokens.toLocaleString('en')} | ${((r.tokens / r.fullTokens) * 100).toFixed(0)}% |`,
    ),
    '',
    '## What this does and does not show',
    '',
    '- Keeping an answer in the text is necessary for a good handoff, not sufficient. Whether the next model actually answers correctly from it is measured by `pnpm eval:handoff` (see handoff-fidelity.md), which needs local models.',
    '- The extraction rules were developed against this same dataset, so these numbers are optimistic for real chats.',
    '- The dataset’s conversations are short (about 390 to 1,100 tokens) and their assistant turns are brief. Real chats have long assistant answers, which the capsule drops except for code, so the token saving on real chats should be larger than shown here.',
    '',
  ];
  const out = values.out ?? path.resolve(here, '../../../../docs/benchmarks/capsule-coverage.md');
  writeFileSync(out, lines.join('\n'));
  console.info(`Wrote ${out}`);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main().catch((err: unknown) => {
    console.error(err);
    process.exit(1);
  });
}
